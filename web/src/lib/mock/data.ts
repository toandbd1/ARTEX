// assetRef biến asset id thành tham chiếu tài sản gắn trên finding (thứ tự lấy label
// giống coverageNodeLabel của backend: URL > tên miền > IP > tên ứng dụng). Cây của
// view "theo tài sản" dựa vào các tham chiếu này để gắn phát hiện lên tài sản.
function assetRef(id: number): FindingAsset {
  const asset = assets.find((candidate) => candidate.id === id);
  if (!asset) throw new Error(`mock assetRef: unknown asset ${id}`);
  return {
    id: String(id),
    type: asset.type,
    label: asset.url || asset.domain || asset.ip || asset.app_name || String(id),
  };
}

